  rep(/(@type":"Product","name":")[^"]*/, `$1${lp.kw}`);
  rep(/("price":")\d+/, `$1${lp.price.replace(/[^\d]/g,"")}`);
  // محتوای H1 و lead
  rep(/<h1>.*?<\/h1>/s, `<h1>${lp.h1line}</h1>`);
  rep(/<p class="lead">[\s\S]*?<\/p>/, `<p class="lead">${lp.lead}</p>`);
